		// rate that starts from rest (the swim), runs at the swim's pace in
		// world units, and gathers to the fall's own opening rate by 30 s;
		// eased to a little over half that while the workings are read, and
		// gathered again to the fall's rate as it opens.
		const rc = geo.rate0;
		const r0 = V_SWIM / Z_NOSE0;
		const DT = 0.01;
		const N = Math.ceil((B.fall[0] + 0.5 - B.swim) / DT);
