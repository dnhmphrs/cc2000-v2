			smooth(span(t, B.swim, B.swim + 1.5)) *
			lerp(r0, rc, smooth(span(t, 24.0, 30.0))) *
			lerp(1, CALC_PACE, smooth(span(t, ...B.slow)) - smooth(span(t, ...B.gather)));
